import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { test } from 'node:test'

test('real processes plan read-only, refuse invalid input, and validate resume with canonical checker', () => {
	const directory = mkdtempSync(resolve('tmp/units/c1-label-driver-fixture-'))
	const id = 'a'.repeat(64)
	const keys = 'b'.repeat(64)
	const packet = join(directory, 'packet.json')
	const item = { id, product: 'Inert text.', evidence: [], rubric: { atoms: [], critical: [], obligations: [] } }
	writeFileSync(packet, JSON.stringify({ protocol: 'c1', items: [item] }))
	mkdirSync(join(directory, 'items'))
	writeFileSync(join(directory, 'items', 'index.json'), JSON.stringify([{ id }]))
	writeFileSync(join(directory, 'items', `${id}.json`), JSON.stringify(item))
	const hash = createHash('sha256').update(readFileSync(packet)).digest('hex')
	const args = ['.orkestrel/agent/tools/c1/main.ts', '--packet', packet, '--packet-hash', hash, '--keys-hash', keys, '--unit', 'fixture', '--cap', '1']
	const before = readdirSync(directory)
	let result = spawnSync(process.execPath, [...args, '--plan'], { encoding: 'utf8' })
	assert.equal(result.status, 0, result.stderr)
	assert.match(result.stdout, /"pending":1/)
	assert.deepEqual(readdirSync(directory), before)
	writeFileSync(join(directory, 'items', `${id}.json`), JSON.stringify({ ...item, product: 'Stale inert text.' }))
	result = spawnSync(process.execPath, [...args, '--plan'], { encoding: 'utf8' })
	assert.equal(result.status, 3)
	assert.match(result.stderr, /split item differs/)
	writeFileSync(join(directory, 'items', `${id}.json`), JSON.stringify(item))
	result = spawnSync(process.execPath, args, { encoding: 'utf8' })
	assert.equal(result.status, 3)
	assert.match(result.stderr, /execution --limit/)
	result = spawnSync(process.execPath, [...args, '--plan', '--limit', '0'], { encoding: 'utf8' })
	assert.equal(result.status, 3)
	assert.match(result.stderr, /positive integer/)
	mkdirSync(join(directory, 'labels'))
	const output = join(directory, 'labels', 'batch-000.json')
	writeFileSync(output, JSON.stringify({ authority: 'root-adjudicated', packet: hash, keys, labels: [{ id, atoms: [], critical: [], obligations: [], ambiguous: [], leaks: [] }] }))
	result = spawnSync(process.execPath, [...args, '--limit', '1'], { encoding: 'utf8' })
	assert.equal(result.status, 0, result.stderr)
	assert.equal(existsSync(join(directory, 'c1-label.lock')), false)
	writeFileSync(output, JSON.stringify({ authority: 'root-adjudicated', packet: hash, keys, labels: [{ id, atoms: [], critical: [], obligations: [], ambiguous: [], leaks: ['product|absent quotation'] }] }))
	result = spawnSync(process.execPath, [...args, '--limit', '1'], { encoding: 'utf8' })
	assert.equal(result.status, 3)
	assert.match(result.stderr, /checker refused/)
	assert.equal(existsSync(join(directory, 'c1-label.lock')), false)
	writeFileSync(output, '{}')
	result = spawnSync(process.execPath, [...args, '--plan'], { encoding: 'utf8' })
	assert.equal(result.status, 3)
	assert.match(result.stderr, /malformed envelope/)
	writeFileSync(join(directory, 'c1-label.lock'), 'explicit recovery required')
	result = spawnSync(process.execPath, [...args, '--limit', '1'], { encoding: 'utf8' })
	assert.equal(result.status, 3)
	assert.match(result.stderr, /EEXIST/)
	assert.equal(readFileSync(join(directory, 'c1-label.lock'), 'utf8'), 'explicit recovery required')
	writeFileSync(join(directory, 'items', 'index.json'), JSON.stringify([{ id }, { id }]))
	result = spawnSync(process.execPath, [...args, '--plan'], { encoding: 'utf8' })
	assert.equal(result.status, 3)
	assert.match(result.stderr, /duplicate item id/)
	writeFileSync(join(directory, 'items', 'index.json'), JSON.stringify([{ id: '../escape' }]))
	result = spawnSync(process.execPath, [...args, '--plan'], { encoding: 'utf8' })
	assert.equal(result.status, 3)
	assert.match(result.stderr, /invalid or duplicate/)
})
